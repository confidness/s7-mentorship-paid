/**
 * Every migration as one script, for pasting into the Supabase SQL Editor.
 *
 *   npm run db:bundle         writes supabase/all-migrations.sql
 *   node scripts/bundle-migrations.mjs --check    fails if that file is out of date (npm run check)
 *   node scripts/bundle-migrations.mjs            prints it
 *
 * The file is committed so it can be opened whole at
 * https://github.com/confidness/s7-mentorship-paid/raw/main/supabase/all-migrations.sql and
 * copied in one go. The first time this was handed over as an attachment, the preview it was
 * copied from showed only its first 150 lines, and the editor was given a script that stopped
 * mid-table. The check keeps the committed copy from drifting behind the migrations.
 *
 * Thirteen files pasted one at a time is thirteen chances to skip one or run them out of order,
 * and a skipped one does not fail loudly: the app keeps working while a policy hole stays open
 * or a dispute event retries for three days. This prints them in numeric order inside a single
 * transaction, so a failure part-way changes nothing, and ends with a query that says, row by
 * row, whether the pieces the code depends on are there.
 *
 * Safe on a database that already has some of them: every file is written to run twice.
 * `alter type … add value` inside a transaction is fine on Postgres 12 and later (Supabase runs
 * 15), and no file uses a value in the same file that adds it.
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const dir = new URL('../supabase/migrations/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')
const files = readdirSync(dir).filter((f) => /^\d+_.*\.sql$/.test(f)).sort()

const out = [
  `-- S7 Mentorship: all ${files.length} migrations, ${files[0]} to ${files.at(-1)}, in order.`,
  '-- Generated by scripts/bundle-migrations.mjs (npm run db:bundle); do not edit by hand.',
  '-- Copy ALL of it — it is long — into Supabase → SQL Editor → Run.',
  '-- One transaction: if any statement fails, nothing is changed.',
  '',
  'begin;',
  '',
]
for (const file of files) {
  out.push(`-- ${'='.repeat(88)}`, `-- ${file}`, `-- ${'='.repeat(88)}`, '', readFileSync(join(dir, file), 'utf8').trimEnd(), '')
}
out.push(
  'commit;',
  '',
  '-- Every row below should say true.',
  "select 'accounts and lessons (0001)' as piece, to_regclass('public.profiles') is not null and to_regclass('public.custom_lessons') is not null as ok",
  "union all select 'progress sync (0002)', to_regclass('public.xp_ledger') is not null",
  "union all select 'projects and reviews (0003)', to_regclass('public.projects') is not null",
  "union all select 'notifications (0004)', to_regclass('public.notifications') is not null",
  "union all select 'demand board (0008)', to_regclass('public.course_requests') is not null",
  "union all select 'chargebacks (0011)', exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid where t.typname = 'order_status' and e.enumlabel = 'charged_back')",
  "union all select 'AI mentor daily limit (0012)', to_regprocedure('public.consume_ai_quota(integer)') is not null",
  "union all select 'lesson hand-ins sent back (0013)', exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid where t.typname = 'submission_status' and e.enumlabel = 'needs_changes');",
  '',
)
const bundle = out.join('\n')
const target = join(dir, '..', 'all-migrations.sql')

if (process.argv.includes('--write')) {
  writeFileSync(target, bundle)
  console.log(`wrote supabase/all-migrations.sql (${files.length} migrations)`)
} else if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    /* missing counts as stale */
  }
  if (current !== bundle) {
    console.log('✗ supabase/all-migrations.sql is out of date with supabase/migrations/. Run `npm run db:bundle` and commit it.')
    process.exit(1)
  }
  console.log(`✓ supabase/all-migrations.sql matches all ${files.length} migrations`)
} else {
  process.stdout.write(bundle)
}
